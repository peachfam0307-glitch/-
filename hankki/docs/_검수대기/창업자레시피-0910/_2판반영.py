브['_검토']['메모'] += ' ／ ⚠️2판: 창업자 지시로 분량을 «반»으로 줄였다. 또띠아 5장의 반은 2.5장이라 «2~3장»으로 적었다 — 소가 남거나 모자라면 알려줘.'

# ── ④ 알룰로스에서 온 아우노슈가 — 환산비를 모른다. 표를 남긴다 ──────────────
알룰로스에서온것 = {'가지 소고기 덮밥': '아우노슈가 1/2큰술',
                '달래 대패삼겹 덮밥': '아우노슈가 1/2큰술',
                '미나리 오징어무침': '아우노슈가 4큰술',
                '우삼겹 두부조림': '아우노슈가 1큰술'}
for r in 편들:
    확인 = []
    x = 알룰로스에서온것.get(r['title'])
    if x and x in r['ingredients']:
        확인.append(x + '  ← 원래 «알룰로스»였다. 아우노슈가로 얼마인지 모른다')
    r['_검토']['분량확인'] = 확인

# 🔒 설탕 잣대가 다 먹었나 — 「아우노슈가」인데 괄호가 없으면 죽는다(알룰로스에서 온 것만 뺀다)
for r in 편들:
    for x in r['ingredients']:
        if '아우노슈가' in x and '(일반설탕' not in x:
            assert x == 알룰로스에서온것.get(r['title']), r['title'] + ' — 「' + x + '」에 일반설탕 분량이 없다'

# ── ⑤ 걸음에서는 괄호를 뺀다 — 앱 실물에서 「(일반설탕 …)」은 «재료에만» 있다 ──────
#    근거 = basics.js 재료 51줄에 있는데 걸음엔 «0줄». 국물떡볶이를 열어보니 걸음은 짧게 쓴다.
#    ⛔ 앱은 걸음에서 「설탕 Y」라고 쓰는데, 창업자가 「설탕」을 빼라 했으므로
#       여기서는 「아우노슈가 X」로 두고 괄호만 뺀다. ← 창업자 확인받을 것
for r in 편들:
    r['steps'] = [re.sub(r'\s*\(일반설탕[^)]*\)', '', x) for x in r['steps']]

json.dump(편들, open(os.path.join(P, 'A-3판.json'), 'w'), ensure_ascii=False, indent=2)
