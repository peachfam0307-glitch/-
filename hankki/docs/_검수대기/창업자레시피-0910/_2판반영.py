# ⛔⛔ 가장 큰 것 — **내가 설탕→아우노슈가를 1:1로 밀었는데 틀렸다.**
#    앱 실물(src/data/basics.js)에 이미 잣대가 있었다:
#      '아우노슈가 1과1/2큰술 (일반설탕 1큰술)' · '아우노슈가 3큰술 (일반설탕 2큰술)'
#      '아우노슈가 3/4작은술 (일반설탕 1/2작은술)' · '아우노슈가 2와1/4큰술 (일반설탕 1과1/2큰술)'
#    ➡️ **아우노슈가 = 설탕 × 1.5**, 그리고 괄호에 «일반설탕 분량»을 같이 적어 둘 다 쓸 수 있게 한다.
#    창업자는 15번만 짚었지만 **같은 잘못이 3·5·8·12·13·14번에도 있었다** — 다 고친다.
#
# ⛔ 알룰로스 → 아우노슈가 환산비는 저장소에 «없다». 내가 정하지 않는다 — 1:1 그대로 두고 물어본다.
import json, os, re
P = os.path.dirname(os.path.abspath(__file__))
편들 = json.load(open(os.path.join(P, 'A-우리재료.json')))
편 = {r['title']: r for r in 편들}


def 갈아(r, 옛, 새, 어디='둘다'):
    """⛔ 못 찾으면 «죽는다» — 조용히 지나가면 「고쳤다」고 잘못 말하게 된다."""
    찾음 = False
    if 어디 in ('둘다', '재료'):
        새목록 = []
        for x in r['ingredients']:
            if 옛 in x:
                찾음 = True
                x = 새.join(x.split(옛))
            새목록.append(x)
        r['ingredients'] = 새목록
    if 어디 in ('둘다', '걸음'):
        새목록 = []
        for x in r['steps']:
            if 옛 in x:
                찾음 = True
                x = 새.join(x.split(옛))
            새목록.append(x)
        r['steps'] = 새목록
    assert 찾음, r['title'] + ' 에서 「' + 옛 + '」를 못 찾았다'


# ── ① 설탕 계열 → 아우노슈가 ×1.5 ＋ 괄호에 일반설탕 분량 ────────────────
설탕고침 = [
    ('보쌈 무김치',        '아우노슈가 1큰술',        '아우노슈가 1과1/2큰술 (일반설탕 1큰술)'),
    ('파기름 간장국수',     '아우노슈가 1작은술',      '아우노슈가 1과1/2작은술 (일반설탕 1작은술)'),
    ('닭목살 불고기',       '아우노슈가 1큰술',        '아우노슈가 1과1/2큰술 (일반설탕 1큰술)'),
    ('미나리 오징어무침',   '아우노슈가 2큰술',        '아우노슈가 3큰술 (일반설탕 2큰술)'),
    ('간장 목살스테이크',   '아우노슈가 3큰술',        '아우노슈가 4와1/2큰술 (일반설탕 3큰술)'),
    ('육회 깻잎무침',      '아우노슈가 1.5큰술',      '아우노슈가 2와1/4큰술 (일반설탕 1과1/2큰술)'),
    ('구움찰떡',          '아우노슈가 54g',          '아우노슈가 81g (일반설탕 54g)'),
]
for 제목, 옛, 새 in 설탕고침:
    갈아(편[제목], 옛, 새)

# ── ② 6번 인분 3 → 2 (창업자) ─────────────────────────────────────
편['우삼겹 두부조림']['servings'] = 2
편['우삼겹 두부조림']['_검토']['추정'] = '시간 25분 · 2인분 · 난이도 쉬움 — 인분은 창업자가 정해줬다'

