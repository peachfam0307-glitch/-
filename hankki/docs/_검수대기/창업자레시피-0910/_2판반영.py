    '닭가슴살 500g', '또띠아 2~3장(20cm)', '새송이버섯 2개(170g)', '파프리카 1개', '양파 1/2개(120g)',
    '스위트콘 1/2캔', '토마토소스 1/2병(300g)', '모짜렐라 치즈 30~40g(장당)',
    '올리브오일 1과1/2큰술(버섯 1/2 + 고기 1)', '소금 1/4작은술(버섯용)', '소금 1/4큰술(고기용)',
    '고춧가루 1큰술', '다진 마늘 3/4큰술', '통후추 약간',
