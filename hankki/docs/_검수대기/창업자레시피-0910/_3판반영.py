# -*- coding: utf-8 -*-
# 🍬 알룰로스 → 아우노슈가 환산 ＋ 아이콘 판정 (창업자 2026-09-10)
#
# 📮 창업자 = "알룰로스 1큰술이면 아우노슈가 1과1/2큰술로 해줘"
#    ➡️ **알룰로스도 ×1.5** — 설탕과 «같은 배수»다.
#    ⛔ 그래서 괄호에 적는 값이 설탕 쪽과 어긋나지 않는다(둘 다 아우노슈가÷1.5).
#       앱 표기를 그대로 따라 「(일반설탕 Y)」로 적는다 — 이미 basics.js 에 있는 꼴이다.
import json, os
P = os.path.dirname(os.path.abspath(__file__))
편들 = json.load(open(os.path.join(P, 'A-3판.json')))
편 = {r['title']: r for r in 편들}


def 갈아(r, 옛, 새):
    """⛔ 못 찾으면 죽는다 — 조용히 지나가면 「고쳤다」고 잘못 말하게 된다."""
    찾음 = False
    for 칸 in ('ingredients', 'steps'):
        새목록 = []
        for x in r[칸]:
            if 옛 in x:
                찾음 = True
                x = 새.join(x.split(옛))
            새목록.append(x)
        r[칸] = 새목록
    assert 찾음, r['title'] + ' 에서 「' + 옛 + '」를 못 찾았다'


# ── ① 알룰로스에서 온 아우노슈가 ×1.5 ─────────────────────────────
# ⛔ 재료엔 괄호를 달고, 걸음엔 괄호 없이(앱 표기 · 2판에서 정한 것)
알룰로스고침 = [
    ('가지 소고기 덮밥',    '아우노슈가 1/2큰술', '아우노슈가 3/4큰술', '(일반설탕 1/2큰술)'),
    ('달래 대패삼겹 덮밥',  '아우노슈가 1/2큰술', '아우노슈가 3/4큰술', '(일반설탕 1/2큰술)'),
    ('우삼겹 두부조림',     '아우노슈가 1큰술',  '아우노슈가 1과1/2큰술', '(일반설탕 1큰술)'),
    ('미나리 오징어무침',   '아우노슈가 4큰술',  '아우노슈가 6큰술',  '(일반설탕 4큰술)'),
]
for 제목, 옛, 새, 괄호 in 알룰로스고침:
    r = 편[제목]
    갈아(r, 옛, 새)
    r['ingredients'] = [(x + ' ' + 괄호) if x == 새 else x for x in r['ingredients']]
    r['_검토']['분량확인'] = []

# ── ② 아이콘 — 창업자가 고른 것 ────────────────────────────────
편['닭가슴살 피자 브리또']['icon'] = 'n2801'   # 치킨부리또

# ── ③ 「새로 뽑아야 하는」 7편 — 지금 아이콘은 «임시»다 ──────────────
뽑을것 = ['가지 소고기 덮밥', '보쌈 무김치', '닭가슴살 오이 샐러드', '대파 소스 목살 덮밥',
        '닭목살 불고기', '달래 대패삼겹 덮밥', '육회 깻잎무침']
for 제목 in 뽑을것:
    편[제목]['_검토']['아이콘'] = '⛔ 새로 뽑아야 한다 — 지금 값(' + 편[제목]['icon'] + ')은 «임시»다'
편['닭가슴살 피자 브리또']['_검토']['아이콘'] = '✅ 창업자가 n2801(치킨부리또)로 골랐다'
편['새송이버섯 들깨무침']['_검토']['아이콘'] = '✅ 창업자 확인 — fe_156 그대로'
편['미나리 오징어무침']['_검토']['아이콘'] = '✅ 창업자 확인 — gr_448 그대로'

# 🔒 아우노슈가인데 괄호가 없으면 죽는다(재료 쪽만)
for r in 편들:
    for x in r['ingredients']:
        assert not ('아우노슈가' in x and '(일반설탕' not in x), r['title'] + ' — 「' + x + '」에 일반설탕 분량이 없다'
# 🔒 걸음엔 괄호가 없어야 한다(앱 표기)
for r in 편들:
    for x in r['steps']:
        assert '(일반설탕' not in x, r['title'] + ' — 걸음에 괄호가 남았다: ' + x

json.dump(편들, open(os.path.join(P, 'A-4판.json'), 'w'), ensure_ascii=False, indent=2)
print('✅ 4판 저장')
for 제목, 옛, 새, 괄호 in 알룰로스고침:
    print('   🍬 ' + 제목 + ' : ' + 옛 + '  →  ' + 새 + ' ' + 괄호 + '   (알룰로스에서)')
print('   🖼 닭가슴살 피자 브리또 : fe_456 → n2801 (치킨부리또)')
print('   ⛔ 새로 뽑을 아이콘 ' + str(len(뽑을것)) + '편: ' + ', '.join(뽑을것))
