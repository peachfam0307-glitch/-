낸것 = []
for i, (원제, 제목, 폴더, 태그, 시간, 인분, 난이도, 재료, 걸음, 메모) in enumerate(편들):
    b = 뼈대[원제]
    낸것.append({
        "id": "basic-own-" + str(i + 1).zfill(3),
        "title": 제목,
        "origin": "창업자",
        "icon": b["icon"],
        "category": "간식" if 폴더 == "간식" else ("양식" if 폴더 == "양식" else "한식"),
        "folder": 폴더,
        "tags": 태그,
        "time": 시간, "servings": 인분, "difficulty": 난이도,
        "ingredients": 재료, "steps": 걸음,
        "_검토": {
            "원래제목": 원제,
            "제목바꿈": 원제 != 제목,
            "추정": "시간 " + str(시간) + "분 · " + str(인분) + "인분 · 난이도 " + 난이도 + " — 원문에 없어 내가 정한 값",
            "메모": 메모,
            "원본출처": b["_검토"]["원본출처"],
        },
    })

# 🔒 지어내지 않았나 — 아는 답으로 대조한다. 하나라도 틀리면 죽는다
assert len(낸것) == 15, "15편이 아니다"
for r in 낸것:
    assert r["ingredients"] and r["steps"], r["title"] + " 가 비었다"
    글 = " ".join(r["steps"]) + " ".join(r["ingredients"])
    # ⛔ 「숟가락으로 떠서」는 «도구»라 괜찮다 — 숫자가 앞에 붙은 «단위»만 잡는다
    남은단위 = re.search(r"[0-9/]\s*(숟가락|스푼)", 글)
    assert not 남은단위, r["title"] + " 에 옛 단위 「" + 남은단위.group(0) + "」가 남았다"
    for 금지 in ("영상", "최광록", "마스터셰프", "저는 "):
        assert 금지 not in 글, r["title"] + " 에 「" + 금지 + "」가 남았다"
    assert r["time"] and r["servings"], r["title"] + " 시간/인분 빔"

