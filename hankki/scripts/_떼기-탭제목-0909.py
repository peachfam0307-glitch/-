# 🧷 탭 제목 글자에서 스티커를 떼어낸다.
# 📮 창업자 2026-09-09 = "글자가 너무 다닥다닥붙어있어서 스티커에서 좀 떼어줘. 내가 글자위에 그냥 붙였거든"
# ⭐ 규칙 = 스티커의 «오른쪽 끝»이 «글자 왼쪽 끝 − 여백» 보다 왼쪽에 오게 한다.
#    ⓐ 먼저 «옮겨서» 해결한다 (창업자가 고른 크기를 지킨다)
#    ⓑ 왼쪽으로 밀다가 카드 밖(0.10)으로 나가면 그때만 «줄인다»
# ⛔ 크기를 먼저 줄이면 창업자가 고른 크기가 조용히 사라진다 — 옮기기가 우선이다.
import json
from PIL import Image

여백 = 0.012        # 글자와 스티커 사이 최소 틈 (화면 폭 대비) = 540px 에서 약 6.5px
왼끝 = 0.10         # 이보다 왼쪽으로는 안 민다 — 카드 밖으로 나간다

글자왼 = {'rec': 0.2148, 'log': 0.2000, 'shop': 0.2056, 'fridge': 0.2056, 'brag': 0.1926}
탭이름 = {'rec': '레시피', 'log': '일기', 'shop': '장보기', 'fridge': '냉장고', 'brag': '레꾸자랑'}

전 = {
    'rec':    {'id': 'cs_b02', 'w': 0.0756, 'x': 0.1644, 'y': 0.0400, 'o': 1},
    'log':    {'id': 'duo101', 'w': 0.1326, 'x': 0.1762, 'y': 0.0315, 'o': 1},
    'shop':   {'id': 'hb09',   'w': 0.1091, 'x': 0.1661, 'y': 0.0362, 'o': 1},
    'fridge': {'id': 'hb12',   'w': 0.1091, 'x': 0.1560, 'y': 0.0371, 'o': 1},
    'brag':   {'id': 'duo301', 'w': 0.1494, 'x': 0.1846, 'y': 0.0324, 'o': 1},
}
후 = {}
for g, c in 전.items():
    오른한계 = 글자왼[g] - 여백
    w = c['w']
    x = 오른한계 - w / 2
    줄임 = None
    if x - w / 2 < 왼끝:              # 왼쪽으로 더 못 민다 → 그때만 줄인다
        w = 오른한계 - 왼끝
        x = 왼끝 + w / 2
        줄임 = round(c['w'], 4), round(w, 4)
    후[g] = {**c, 'w': round(w, 4), 'x': round(x, 4)}
    print(f"{탭이름[g]:5s} x {c['x']:.4f}→{x:.4f}"
          + (f" · 크기 {줄임[0]}→{줄임[1]} (밀어서는 안 됐다)" if 줄임 else " · 크기 그대로"))
json.dump(후, open('/tmp/탭배치.json', 'w'), ensure_ascii=False)
