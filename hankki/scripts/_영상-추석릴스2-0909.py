#   🔎 뿌리 = 조각이 작고(폭 0.09~0.18) 반투명(0.65~0.90)이라 1080폭에서 «점»으로 보인다.
#      1판은 앱 화면을 «있는 그대로» 흘려보내기만 해서, 봐야 할 것을 아무도 못 찾는다.
#   ✅ 그래서 셋을 바꿨다:
#      ① **없던 것이 생기는 걸** 보여준다 — 민판(장식 없는 홈)에서 조각이 톡톡 나타난다
#      ② **확대**한다 — 보름달·한복 곰펭·탭 상단바를 화면 가득 채운다
#      ③ 나타날 때 **반짝 터짐**을 준다 — 눈이 그리로 간다
