import json, math, os, subprocess
from PIL import Image, ImageDraw

재 = '/tmp/추석릴스'
낼 = f'{재}/합성2'
os.makedirs(낼, exist_ok=True)
W, H, FPS = 1080, 1920, 30

민 = Image.open(f'{재}/홈-민판.png').convert('RGBA')
SW, SH = 민.size                      # 1170 x 2532
탭그림 = {n: Image.open(f'{재}/탭-{n}.png').convert('RGBA') for n in ('레시피','일기','장보기','냉장고','레꾸자랑')}
자막 = {k: Image.open(f'{재}/{k}.png').convert('RGBA') for k in ('c1','c2','c3','c4','c5')}

# 🧩 조각 — seasonDecor.js 의 추석 값 그대로. ⛔여기서 숫자를 만들지 않는다.
조각 = [
    {'id':'추석소품01','o':.70,'w':.1822,'x':.7914,'y':.0883},
    {'id':'duo301',   'o':.80,'w':.1513,'x':.5432,'y':.4240},
    {'id':'추석소품01','o':.90,'w':.0925,'x':.2879,'y':.8109},
    {'id':'duo401',   'o':.85,'w':.1712,'x':.4980,'y':.8802},
]
컷 = {c['id']: Image.open(f'/home/user/hankki/hankki/src/assets/stickers/season/{c["id"]}.webp').convert('RGBA')
      for c in 조각}

def 별(그림, cx, cy, r, 알파):
    d = ImageDraw.Draw(그림, 'RGBA')
    for 배, 굵비, 색, 세기 in ((1.18,.20,(176,116,26),.85),(1.00,.17,(245,196,81),1.0),(.52,.13,(255,253,245),1.0)):
        R, 굵 = r*배, r*배*굵비
        d.polygon([(cx,cy-R),(cx+굵,cy-굵),(cx+R,cy),(cx+굵,cy+굵),
                   (cx,cy+R),(cx-굵,cy+굵),(cx-R,cy),(cx-굵,cy-굵)],
                  fill=(*색, int(min(255, 알파*세기))))

def 홈판(t, 나온몫):
    """민판 위에 조각을 «나온 만큼» 얹는다. 나온몫 = 0(없음) ~ 1(다 나옴)"""
    바 = 민.copy()
    for i, c in enumerate(조각):
        문 = min(1.0, max(0.0, 나온몫*len(조각) - i))      # 하나씩 차례로
        if 문 <= 0: continue
        # 톡 — 1.35배로 튀어나왔다 제자리로(가만히 나타나면 눈에 안 띈다)
        튐 = 1 + 0.35*(1-문)**2 * math.sin(문*math.pi*1.6)
        im = 컷[c['id']]
        w = int(c['w']*SW*튐); h = int(im.height*w/im.width)
        조 = im.resize((max(1,w), max(1,h)))
        조.putalpha(조.getchannel('A').point(lambda v: int(v*c['o']*문)))
        바.alpha_composite(조, (int(c['x']*SW-w/2), int(c['y']*SH-h/2)))
        # ✨ 나타나는 순간 터짐
        if 문 < 1:
            for n in range(8):
                각 = 2*math.pi*n/8
                거리 = c['w']*SW*(0.55+0.75*문)
                별(바, c['x']*SW+math.cos(각)*거리, c['y']*SH+math.sin(각)*거리,
                   c['w']*SW*0.16*(1-문)+8, 250*(1-문))
    return 바

def 잘라(바, 배율=1.0, 중심=(0.5, 0.42)):
    """9:16 으로 자른다. 배율>1 이면 그만큼 «확대»(＝좁게 자른다)."""
    ch = min(SH, SW/(W/H))/배율
    cw = ch*(W/H)
    cx, cy = 중심[0]*SW, 중심[1]*SH
    l = min(max(0, cx-cw/2), SW-cw); tp = min(max(0, cy-ch/2), SH-ch)
    return 바.crop((int(l), int(tp), int(l+cw), int(tp+ch))).resize((W, H), Image.LANCZOS)

def 부드(r):    # 0~1 을 부드럽게
    return r*r*(3-2*r)

# ⏱ 짜임 — 「없던 것이 생긴다 → 크게 본다 → 탭마다 다르다 → 마무리」
자막판 = [('c1',0.2,1.5,0.62,'가운데'), ('c2',2.0,3.5,0.62,'가운데'),
          # ⛔ y .055 는 «상단바 애들 바로 위»라 자막이 애들을 가렸다(2026-09-09 시안에서 눈으로 잡았다)
          ('c3',8.8,13.2,0.660,'왼쪽'), ('c4',13.9,15.8,0.40,'가운데')]
탭순 = ['레시피','일기','장보기','냉장고','레꾸자랑']
총초 = 16.0
for f in range(int(총초*FPS)):
    t = f/FPS
    if t < 1.6:                                   # ① 민판
        프 = 잘라(홈판(t, 0))
    elif t < 3.8:                                 # ② 톡톡 등장
        프 = 잘라(홈판(t, 부드(min(1,(t-1.6)/1.7))))
    elif t < 6.1:                                 # ③ 보름달 확대
        r = 부드((t-3.8)/2.3)
        프 = 잘라(홈판(t,1), 1+1.9*r, (0.5+(0.7914-0.5)*r, 0.42+(0.0883-0.42)*r))
    elif t < 8.5:                                 # ④ 한복 곰펭 확대
        r = 부드(min(1,(t-6.1)/1.1))
        프 = 잘라(홈판(t,1), 2.9-0.5*r, (0.7914+(0.5432-0.7914)*r, 0.0883+(0.4240-0.0883)*r))
    elif t < 13.6:                                # ⑤ 탭 다섯 — 상단바를 크게
        i = min(4, int((t-8.5)/1.02))
        # ⛔ 가만히 있는 그림 다섯 장은 «죽은 화면»으로 보인다 — 탭마다 아주 천천히 들어간다.
        속 = ((t-8.5) % 1.02)/1.02
        프 = 잘라(탭그림[탭순[i]], 2.30+0.16*속, (0.30, 0.062))
    else:                                         # ⑥ 마무리 — «같은 그림»에서 멀어진다
        # ⛔ 1판은 여기서 탭 그림 → 홈 그림으로 «툭» 갈아탔다. 같은 장면에서 빠져야 안 튄다.
        r = 부드(min(1,(t-13.6)/1.6))
        프 = 잘라(탭그림['레꾸자랑'], 2.46-1.46*r, (0.30+(0.5-0.30)*r, 0.062+(0.30-0.062)*r))

    for 키, 시, 끝, y, 맞춤 in 자막판:
        if not (시 <= t <= 끝): continue
        c = 자막[키]
        a = min(1.0,(t-시)/0.26,(끝-t)/0.26)
        x = 64 if 맞춤=='왼쪽' else (W-c.width)//2
        칸 = c.copy(); 칸.putalpha(칸.getchannel('A').point(lambda v:int(v*max(0,a))))
        프.alpha_composite(칸, (x, int(y*H)+int(24*(1-min(1,(t-시)/0.32)))))
    프.convert('RGB').save(f'{낼}/{f+1:04d}.png')
print('합성2', int(총초*FPS), '칸')
