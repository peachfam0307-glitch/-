// 🔖🔖 **핀은 두 종이다 — 여기 «한 곳»에서만 정한다** (창업자 확정 2026-09-08)
//
// 📮 창업자 = *"요리사모자는 해볼것, 하트는 최애 두 종으로 가자"*
//    ＋ *"종류서랍은(필터줄) 2줄로 가도 좋을 것 같아"*
//    ＋ *"윗줄은 해볼것, 최애, SNS 자주만든것/ 아래는 한식 양식 등등.."*
//
// ⛔⛔ **저장을 «넓히지» 않는다 — 이게 이 파일의 존재 이유다.**
//   `r.favorite` 는 **참/거짓 그대로** 둔다(「꽂혔나」). 종은 `r.favPin` 에 «곁에» 담는다.
//   🔢 실측 = `.favorite` 를 읽는 곳이 코드에 **12군데**(시드 병합 · 백업 · 설정 통계 · 상세 · 목록 · 해볼 것 화면).
//      참/거짓을 「어떤 핀인가」로 바꾸면 그 12군데가 «전부» 옛 판 `true` 를 못 읽는 순간이 생긴다.
//   ⭐⭐ 실패의 모양이 다르다(절대원칙 34) —
//      · 지금 실패 = 잘못 눌러 한 편이 빠진다 → 다시 누르면 복구
//      · 넓혔다 실패 = **몇 달 모은 핀이 통째로 사라진다** → 복구 불가
//      2026-08-04 「빈 표지」 사고와 같은 뿌리다 — **없는 값으로 덮으면 그건 지우는 것이다.**
//   ✅ 그래서 `favPin` 이 «없으면» 요리사모자다. 이미 깔린 폰은 **한 줄도 안 바뀌고 그대로 돈다.**
//
// ⭐ 이름을 여기 두는 이유는 `favName.js` 와 같다 — 이 자리는 벌써 두 번 이름이 바뀌었다
//   (즐겨찾기 → 책갈피 → 해볼 것). 한 곳만 고치면 말이 갈라진다.
import { FAV_NAME } from './favName'

/** 기본 종 — `favPin` 이 없는 옛 레시피는 «전부» 이것이다. ⛔ 값을 바꾸지 말 것(옛 폰이 갈린다). */
export const PIN_DEFAULT = 'chef'

// 🔖 종의 «뜻» — 색만 다른 핀은 유저가 뭘 꽂았는지 못 외운다(30편이면 30번 기억해야 하는 짐).
//   · 요리사모자 = **해볼 것**(아직 안 해봤지만 하고 싶은 것)
//   · 하트 = **최애**(이미 해봤고 좋았던 것)
//   ⏳ 하트 그림은 «아직 없다» — 창업자가 클립 컷을 새로 뽑는 중(2026-09-08).
//      ⛔ 그림이 오기 전엔 이 종이 화면에 «안 뜬다»(꽂힌 게 0개면 칩이 안 선다) — 반쪽짜리 UI 를 내보내지 않는다.
export const FAV_PINS = [
  { key: 'chef', name: FAV_NAME },
  { key: 'heart', name: '최애' },
]

const KEYS = new Set(FAV_PINS.map((p) => p.key))

/** 레시피 → 종 열쇠. 모르는 값·빈 값은 «전부» 기본 종이다(옛 폰 안전). */
export const pinOf = (r) => (KEYS.has(r?.favPin) ? r.favPin : PIN_DEFAULT)

/** 그 종으로 꽂혀 있나 — 「꽂혔나(favorite)」와 「어떤 종인가(favPin)」를 «둘 다» 본다. */
export const isPinned = (r, key) => !!r?.favorite && pinOf(r) === key

/** 유저에게 보이는 이름 */
export const pinName = (key) => FAV_PINS.find((p) => p.key === key)?.name || FAV_NAME
