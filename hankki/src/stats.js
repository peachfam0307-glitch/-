// 🖼🖼 **화면 기록** — 「뭘 많이 썼나」를 재는 자리 (2026-09-08)
//
// 📮 창업자 = *"내일부터는 우리앱에서 뭘 많이 썼는지도 다 볼수있어?"*
//            *"이걸 지금부터 재야 향후 기능추가나 업뎃할때 이용하지"*
//
// ⛔⛔ **왜 「저절로」는 안 되나** — 우리 앱은 화면을 바꿔도 **주소가 안 바뀐다**.
//    GA4 는 주소로 화면을 가르는데 우리는 전부 같은 주소라 「한끼를 열었다」로만 뭉친다.
//    그래서 화면 이름을 «우리가» 하나씩 보낸다.
//
// 🔒🔒 **나가는 건 아래 목록에 «있는 이름 하나»뿐이다.**
//    ⛔ 레시피 제목·일기 글·사진·검색어는 절대 안 나간다.
//    ⛔ 목록에 없는 이름이 오면 **안 보낸다**(`기타` 로도 안 바꾼다 — 없는 걸 지어내지 않는다).
//    이 자물쇠가 있어야 나중에 화면이 늘어도 «모르는 사이에» 새 값이 새 나가지 않는다.
const 보내도되는화면 = new Set([
  // 아래 일곱 = 탭 (src/App.jsx 의 TABS)
  'home', 'search', 'myrecipes', 'log', 'shop', 'brag', 'profile',
  // 아래 여덟 = 위로 쌓이는 화면 (src/App.jsx 의 case 목록)
  'import', 'detail', 'editor', 'inbox', 'favorites', 'cooked', 'cook', 'diary',
])

let 지난화면 = null

/**
 * 🖼 지금 보는 화면을 한 번 적는다.
 * ⛔ 같은 화면이 이어지면 «안» 보낸다 — 화면 안에서 내용만 바뀌는 것(일기 넘겨보기)까지 세면 숫자가 부푼다.
 * ⛔ 통계를 끈 사람에게는 아무 일도 안 일어난다.
 */
export function 화면봄(이름) {
  if (!MEASUREMENT_ID) return
  if (!보내도되는화면.has(이름)) return   // 🔒 자물쇠
  if (이름 === 지난화면) return
  지난화면 = 이름
  보내기(이름)
}

// ⛔⛔ **[2026-09-08 실측으로 잡았다] `screen_view` 로 보내면 «안 잡힌다».**
//    🔢 근거 = `screen_view` 는 GA4 의 **예약된 이름**이고 **앱(네이티브) 스트림의 것**이다.
//       우리는 웹(TWA)이라 **웹 스트림**이고, 웹의 짝은 `page_view` 다.
//       (support.google.com 은 이 환경에서 못 열어 공식 원문을 직접 못 봤다 — 여러 경로로 같은 말을 확인했다)
//    ⛔ 그대로 뒀으면 **콘솔에 화면 숫자가 0 으로 나왔을 것이다.** 그런데 앱은 멀쩡하니 아무도 몰랐을 것이다.
//
// ⭐⭐ **그래서 `page_view` 로 보내고, 화면 이름을 «페이지 제목»에 싣는다.**
//    이러면 창업자가 **[보고서] → [참여도] → [페이지 및 화면]** 에서 «그냥» 볼 수 있다.
//    ⛔ 맞춤 이벤트(`hankki_screen` 같은 것)로 갔으면 **맞춤 측정기준을 따로 등록해야** 보여서
//       내일 아침에 아무것도 못 봤을 것이다. 표준 이벤트라야 표준 보고서에 뜬다.
//    📌 주소에 `#화면이름` 을 붙이는 건 «구분용»이다 — 실제로 그 주소로 옮기지 않는다.
function 보내기(이름) {
  try {
    if (통계꺼짐()) return
    if (typeof window.gtag !== 'function') { 못보낸화면 = 이름; return }  // 아직 안 붙었다 — 붙으면 그때 보낸다
    못보낸화면 = null
    window.gtag('event', 'page_view', {
      page_title: 이름,
      page_location: `${location.origin}${location.pathname}#${이름}`,
    })
  } catch { /* ⛔ 통계가 죽어도 앱은 그대로 돈다 */ }
}
let 못보낸화면 = null

// ═══════════════════════════════════════════════════════════════════
// 🔀🔀 **끄는 자리는 «방침 페이지» 안이다** (2026-09-08)
//
// 📮 창업자 = *"우리도 깊이 묻어놓자"* · *"설정에서 딱 안보이게"* · *"개인정보처리방침안에 넣거나"*
//
// ⛔ 없앨 수는 없다 — Google Analytics 약관 7조(거부 수단을 우회하지 말 것) ＋
//    Play 「사용자 데이터」 정책(필수가 아닌 데이터는 켜고 끌 수 있어야 한다).
//    ⭐ 그래서 «없애기»가 아니라 «깊이 묻기»로 갔다. 카카오톡도 4단계 깊이에 있다.
//
// ⛔⛔ **문제 하나 — 방침은 «다른 탭»에서 열린다**(설정 → 개인정보처리방침 → 새 탭).
//    거기서 껐는데 앱 탭은 여전히 gtag 를 켜둔 채 돌고 있으면 **끈 뒤에도 계속 보낸다.**
//    ⭐ 그건 방침이 「언제든 중단하실 수 있습니다」라고 «거짓말»을 하는 것이다.
// ✅ 같은 주소(같은 출처)라 브라우저가 `storage` 신호를 보내 준다 — 그걸 듣고 그 자리에서 멎는다.
//    📌 `storage` 는 «다른 탭»이 바꿀 때만 온다(같은 탭에서 바꾸면 안 온다) — 여기선 그게 맞다.
try {
  window.addEventListener('storage', (e) => {
    if (e && e.key !== null && e.key !== 열쇠) return   // 다른 열쇠는 무시 (key===null = 통째로 비운 것)
    try { 통계끄기설정(통계꺼짐()) } catch { /* noop */ }
  })
} catch { /* ⛔ 통계가 죽어도 앱은 그대로 돈다 */ }
