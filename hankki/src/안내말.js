// 🔑🔑 **까닭 → 말** — 「어떤 오류에 어떤 안내」의 «유일한» 구현 [창업자 2026-09-09]
//   📮 창업자 = "어떤 오류에 어떤 안내가 들어가고 열쇠는 어떻게 되는지 세밀하게 설계해서 남겨"
//   📖 표 = docs/열쇠와안내-까닭별-2026-09-09.md
//
//   ⛔⛔ **말을 다른 곳에 또 적지 않는다** — 두 곳에 적으면 반드시 갈라진다.
//   ⛔ 「열쇠는 그대로예요」는 «안 깎인 것이 사실일 때»만 붙는다. 서버가 보낸 값으로만 판단한다.
//      그래서 «모름»(끊김)일 때는 열쇠 얘기를 통째로 뺀다 — 모르는 걸 안다고 말하는 게 최악이다.
export function 까닭말(왜, 앎 = true) {
  if (!앎) return { 머리: '연결이 끊겼어요', 몸: '잠시 뒤에 다시 해 주세요', 열쇠말: '' }
  switch (왜) {
    case '빈손':
      return { 머리: '글자가 안 보여요', 몸: '밝은 곳에서 다시 찍어 주세요', 열쇠말: '열쇠는 그대로예요' }
    case '전에읽음':
      return { 머리: '전에 읽은 사진이에요', 몸: '그대로 채웠어요', 열쇠말: '열쇠 안 썼어요' }
    case '처리중':
      return { 머리: '아직 읽는 중이에요', 몸: '조금 뒤에 다시 해 주세요', 열쇠말: '열쇠는 그대로예요' }
    case '구글실패':
      return { 머리: 'AI가 잠깐 안 돼요', 몸: '조금 뒤에 다시 해 주세요', 열쇠말: '열쇠는 그대로예요' }
    case 'rate_limited':
      return { 머리: '너무 빨라요', 몸: '1분 뒤에 다시 해 주세요', 열쇠말: '열쇠는 그대로예요' }
    case 'global_quota':
      return { 머리: '오늘은 여기까지예요', 몸: '내일 다시 열려요', 열쇠말: '열쇠는 그대로예요' }
    case 'user_quota':
      return { 머리: '이번 달 무료 열쇠를 다 썼어요', 몸: '다음 달에 다시 채워져요', 열쇠말: '' }
    default:
      // ⛔ 모르는 까닭이 와도 «막다른 길»이 되면 안 된다 — 열쇠 얘기는 안 하고 할 일만 말한다.
      return { 머리: '잘 안 됐어요', 몸: '조금 뒤에 다시 해 주세요', 열쇠말: '' }
  }
}

// 🤖 AI 다듬기가 «끝났을 때» 하얀 창에 남는 말 — 사라지기만 하면 됐는지 안 됐는지 모른다.
export function 다듬기끝말(됐나) {
  return 됐나
    ? { 머리: '다 됐어요', 몸: '레시피에 올라갔어요', 열쇠말: '' }
    : { 머리: 'AI 다듬기가 안 됐어요', 몸: '임시보관함에서 「AI로 다듬기」를 한 번 더 눌러 주세요', 열쇠말: '열쇠는 안 써요' }
}
